def expand(design: dict) -> list[str]:
    """Full rows (mirror halves, apply patches)."""
    rows = list(design["rows"])
    if design.get("half"):
        rows = [r + r[-2::-1] for r in rows]
    grid = [list(r) for r in rows]
    for letter, seq in design.get("stripes", {}).items():
        for y, r in enumerate(grid):
            for x, c in enumerate(r):
                if c == letter:
                    r[x] = seq[(x + y) % len(seq)]
    for y, x, c in design.get("patch", []):
        grid[y][x] = c
    return ["".join(r) for r in grid]


def check(design: dict) -> None:
    rows = expand(design)
    w = len(rows[0])
    bad = [i for i, r in enumerate(rows) if len(r) != w]
    if bad:
        raise ValueError(f"{design['title']}: rows {bad} are not {w} wide")
    missing = {c for r in rows for c in r} - set(design["colors"])
    if missing:
        raise ValueError(f"{design['title']}: letters without a color: {missing}")
